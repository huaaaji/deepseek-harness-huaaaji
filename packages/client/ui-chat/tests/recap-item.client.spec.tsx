// @vitest-environment jsdom
import { afterEach, describe, expect, it } from 'vitest'
import { cleanup, fireEvent, render } from '@testing-library/react'
import { makeTranslate } from '@deepseek-ai/dsh-client-test-runtime'
import { brandString } from '@deepseek-ai/dsh-brand'
import { en as commonEn } from '@deepseek-ai/dsh-client-locale/src/locales/en.ts'
import { zh as commonZh } from '@deepseek-ai/dsh-client-locale/src/locales/zh.ts'
import type { SessionRecapProviderId } from '@deepseek-ai/dsh-session-recap/types'
import { en, zh } from '../src/client/locale.ts'
import { RecapItem } from '../src/client/chat/RecapItem.tsx'
import type { RecapChatData } from '../src/client/contract/chat-nodes.ts'

afterEach(cleanup)

const EN = makeTranslate(en, commonEn)
const ZH = makeTranslate(zh, commonZh)
const provider = (id: string): SessionRecapProviderId => brandString<SessionRecapProviderId>(id)

function recap(overrides: Partial<RecapChatData> = {}): RecapChatData {
  return {
    seq: 7,
    time: 1_700_000_000_000,
    text: 'Fixed the login redirect.',
    source: { kind: 'provider', provider: provider('session-summarizer') },
    turnRange: { first: 3, last: 3 },
    ...overrides,
  }
}

describe('RecapItem', () => {
  it('previews the recap in one row and discloses a single covered turn', () => {
    const view = render(<RecapItem node={recap()} t={EN} />)
    const toggle = view.getByRole('button')

    expect(view.getByText('Session recap')).toBeDefined()
    expect(toggle.textContent).toContain('Fixed the login redirect.')
    expect(toggle.getAttribute('aria-expanded')).toBe('false')
    expect(view.queryByText(/Covers/)).toBeNull()

    fireEvent.click(toggle)
    expect(toggle.getAttribute('aria-expanded')).toBe('true')
    // The disclosure carries the whole sentence beside the turns and source.
    expect(view.getAllByText('Fixed the login redirect.')).toHaveLength(2)
    expect(view.getByText('Covers turn 3 · Generated by session-summarizer')).toBeDefined()

    fireEvent.click(toggle)
    expect(toggle.getAttribute('aria-expanded')).toBe('false')
    expect(view.queryByText(/Covers/)).toBeNull()
  })

  it('names the covered range and the model route when one produced the recap', () => {
    const text = 'Moved the export flow onto the queue.'
    const view = render(<RecapItem
      node={recap({
        text,
        source: {
          kind: 'provider',
          provider: provider('session-summarizer'),
          model: { provider: 'deepseek', model: 'deepseek-chat' },
        },
        turnRange: { first: 2, last: 5 },
      })}
      t={EN}
    />)

    fireEvent.click(view.getByRole('button'))
    expect(view.getByText('Covers turns 2–5 · Generated by session-summarizer (deepseek-chat)')).toBeDefined()
    expect(view.getAllByText(text)).toHaveLength(2)
  })

  it('localizes every label for a provider without a model', () => {
    const text = '修复了登录跳转。'
    const view = render(<RecapItem node={recap({ text })} t={ZH} />)

    expect(view.getByText('会话回顾')).toBeDefined()
    expect(view.getByRole('button').textContent).toContain(text)

    fireEvent.click(view.getByRole('button'))
    expect(view.getByText('覆盖第 3 轮 · 由 session-summarizer 生成')).toBeDefined()
    expect(view.getAllByText(text)).toHaveLength(2)
  })
})
